export function describeRequest(path: string) {
  const pathname = path.split(/[?#]/)[0] || "";
  const route = routes.find((template) => {
    const expected = template.split("/");
    const actual = pathname.split("/");
    return expected.length === actual.length && expected.every((part, i) => part.startsWith(":") ? !!actual[i] : part === actual[i]);
  });
  return { route: route ?? "", requestName: route?.replace(/:([\w]+)/g, "by_$1").replace(/[^\w]+/g, ".").replace(/^\.|\.$/g, "") || "unmatched" };
}

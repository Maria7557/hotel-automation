import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { build } from "esbuild";

const root = resolve(import.meta.dirname, "../../..");
export async function buildBrowserMonitoring() {
  const result = await build({ entryPoints: [resolve(root, "packages/monitoring/src/browser.ts")], bundle: true, write: false,
    platform: "browser", format: "iife", globalName: "OspioSignalRuntime", target: "es2022", minify: true });
  await writeFile(resolve(root, "apps/server/src/monitoring/browser-bundle.ts"), "// Generated by scripts/build-browser-monitoring.ts; edit packages/monitoring/src/browser.ts.\nexport const browserBundle = " + JSON.stringify(result.outputFiles[0]!.text) + ";\n");
}
if (process.argv[1] === import.meta.filename) await buildBrowserMonitoring();
